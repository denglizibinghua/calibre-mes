CREATE TABLE IF NOT EXISTS ai_request_audit (
  audit_id bigint GENERATED BY DEFAULT AS IDENTITY,
  request_id varchar(64) NULL,
  session_id varchar(64) NULL,
  user_id bigint NOT NULL,
  operation varchar(32) NOT NULL,
  question_hash char(64) NULL,
  data_scope varchar(16) NULL,
  data_time_range varchar(128) NULL,
  model varchar(128) NULL,
  sources_json text NULL,
  input_summary varchar(2000) NULL,
  status varchar(24) NOT NULL,
  fallback boolean NOT NULL DEFAULT false,
  latency_ms bigint NULL,
  error_code varchar(64) NULL,
  created_at timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (audit_id)
);

DO $$
BEGIN
  IF to_regclass('idx_ai_audit_user_time') IS NULL THEN
    CREATE INDEX idx_ai_audit_user_time ON ai_request_audit (user_id, created_at);
  END IF;
  IF to_regclass('idx_ai_audit_request') IS NULL THEN
    CREATE INDEX idx_ai_audit_request ON ai_request_audit (request_id);
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS ai_knowledge_document (
  document_id bigint GENERATED BY DEFAULT AS IDENTITY,
  source varchar(512) NOT NULL,
  content_hash char(64) NOT NULL,
  chunk_count integer NOT NULL DEFAULT 0,
  index_status varchar(24) NOT NULL DEFAULT 'PENDING',
  last_modified_at timestamp(0) without time zone NULL,
  indexed_at timestamp(0) without time zone NULL,
  error_message varchar(1000) NULL,
  PRIMARY KEY (document_id),
  CONSTRAINT uk_ai_knowledge_source UNIQUE (source)
);

DO $$
BEGIN
  IF to_regclass('idx_ai_knowledge_status') IS NULL THEN
    CREATE INDEX idx_ai_knowledge_status ON ai_knowledge_document (index_status);
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS ai_knowledge_index_task (
  task_id varchar(64) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'QUEUED',
  max_chars integer NOT NULL,
  overlap_chars integer NOT NULL,
  scanned_files integer NOT NULL DEFAULT 0,
  files_changed integer NOT NULL DEFAULT 0,
  files_skipped integer NOT NULL DEFAULT 0,
  files_deleted integer NOT NULL DEFAULT 0,
  chunks_indexed integer NOT NULL DEFAULT 0,
  chunks_total integer NOT NULL DEFAULT 0,
  failures_json text NULL,
  message varchar(1000) NULL,
  created_at timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at timestamp(0) without time zone NULL,
  finished_at timestamp(0) without time zone NULL,
  PRIMARY KEY (task_id)
);

DO $$
BEGIN
  IF to_regclass('idx_ai_knowledge_task_status') IS NULL THEN
    CREATE INDEX idx_ai_knowledge_task_status ON ai_knowledge_index_task (status, created_at);
  END IF;
END
$$;

