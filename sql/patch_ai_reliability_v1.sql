-- Apply this patch to an existing MES database before enabling the reliability features.
-- PostgreSQL 16 / psql: every schema change is guarded so the patch can be safely re-run.
SET client_encoding TO 'UTF8';

CREATE TABLE IF NOT EXISTS ai_plan_suggestion (
  plan_id bigint GENERATED BY DEFAULT AS IDENTITY,
  plan_uuid varchar(64) NOT NULL,
  operator_id bigint NOT NULL,
  question varchar(2000) NOT NULL,
  summary text NULL,
  affected_orders_json text NULL,
  constraints_json text NULL,
  risk_level varchar(16) NULL,
  status varchar(32) NOT NULL DEFAULT 'PENDING_CONFIRMATION',
  created_at timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmed_at timestamp(0) without time zone NULL,
  confirmed_by bigint NULL,
  PRIMARY KEY (plan_id),
  CONSTRAINT uk_ai_plan_uuid_operator UNIQUE (plan_uuid, operator_id)
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = current_schema() AND table_name = 'sys_user'
                   AND column_name = 'work_unit_id') THEN
    ALTER TABLE sys_user ADD COLUMN work_unit_id bigint NULL;
  END IF;
END
$$;

DO $$
BEGIN
  IF to_regclass('idx_sys_user_work_unit') IS NULL THEN
    CREATE INDEX idx_sys_user_work_unit ON sys_user (work_unit_id);
  END IF;
END
$$;

