-- ============================================================================
-- Bike Assembly MES — 数据库全量初始化脚本（PostgreSQL 16）
-- File: sql/init_database.sql
-- Version: 4.0 (MySQL 8 → PostgreSQL 16; 业务数据另执行 dev_seed_full.sql)
-- Date: 2026-11-15
-- ============================================================================
-- ⚠️  警告：本脚本会删除现有表和数据，仅适用于开发、测试和答辩演示环境！
-- ⚠️  禁止直接用于有真实数据的生产数据库！
-- ============================================================================
-- 用途:
--   1. 删除全部现有表（DROP TABLE ... CASCADE）
--   2. 创建全部 32 张表
--   3. 创建全部外键约束、唯一索引、生成列、updated_at 触发器
--   4. 插入角色、菜单、权限、管理员用户、系统配置种子数据
-- ============================================================================
-- 执行命令（在容器内或用本机 psql）:
--   docker cp sql/init_database.sql xiaoxueqi-pgvector-1:/tmp/init_database.sql
--   docker exec xiaoxueqi-pgvector-1 psql -U mes -d bike_assembly_mes \
--     -v ON_ERROR_STOP=1 -f /tmp/init_database.sql
-- ============================================================================
-- 数据库: bike_assembly_mes (预先创建，UTF8，LC_COLLATE=C)
-- ============================================================================
-- 类型映射: 见 sql/pg-migration-notes.md
--   BIGINT AUTO_INCREMENT      → bigint GENERATED BY DEFAULT AS IDENTITY
--   DATETIME                   → timestamp(0) without time zone
--   JSON                       → text（Java String 绑定 + LIKE 查询，禁止 jsonb）
--   TINYINT 标志位（Java Boolean） → boolean；其余 TINYINT → smallint
--   ON UPDATE CURRENT_TIMESTAMP → BEFORE UPDATE 触发器 set_updated_at()
-- ============================================================================
-- 密码加密方式: BCrypt (Spring Security BCryptPasswordEncoder, cost=10)
-- 开发密码 Demo@123456 → $2b$10$rTom51Fr.4SmIIh/OrFleu75ZL3VH0j8uCvudJz49k4kKhYSzRBNS
-- ============================================================================

