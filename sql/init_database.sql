-- ==================== 5. updated_at 触发器 ====================
-- MySQL 的 ON UPDATE CURRENT_TIMESTAMP 在 PostgreSQL 中由 BEFORE UPDATE 触发器实现。
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  -- 等价 MySQL 的 ON UPDATE CURRENT_TIMESTAMP：只有调用方没有显式改写时间列时才自动刷新。
  -- 无条件覆盖会破坏「显式把 updated_at 回拨以模拟租约过期」的场景（幂等超时接管）。
  IF TG_ARGV[0] = 'updated_at' THEN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
      NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;
  ELSE
    IF NEW.update_time IS NOT DISTINCT FROM OLD.update_time THEN
      NEW.update_time := CURRENT_TIMESTAMP;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sys_config_touch BEFORE UPDATE ON sys_config
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_base_bom_touch BEFORE UPDATE ON base_bom
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_base_route_touch BEFORE UPDATE ON base_route
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_wms_inventory_touch BEFORE UPDATE ON wms_inventory
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_pro_idempotency_touch BEFORE UPDATE ON pro_idempotency_record
  FOR EACH ROW EXECUTE FUNCTION set_updated_at('updated_at');

