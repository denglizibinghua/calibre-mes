-- ==================================================================
-- 2.1 系统管理模块 (sys_*)
-- ==================================================================

-- 系统管理 / 角色表
CREATE TABLE sys_role (
  role_id bigint GENERATED BY DEFAULT AS IDENTITY,
  role_name varchar(64) NOT NULL,
  role_key varchar(64) NOT NULL,
  data_scope varchar(16) NOT NULL DEFAULT 'SELF',
  status char(1) NOT NULL DEFAULT '0',
  create_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (role_id),
  CONSTRAINT uk_sys_role_role_key UNIQUE (role_key)
);

-- 系统管理 / 菜单权限表（含管理端动态路由字段）
CREATE TABLE sys_menu (
  menu_id bigint GENERATED BY DEFAULT AS IDENTITY,
  parent_id bigint NOT NULL DEFAULT 0,
  menu_name varchar(64) NOT NULL,
  path varchar(128) NULL,
  component varchar(255) NULL,
  icon varchar(64) NULL,
  visible char(1) NOT NULL DEFAULT '1',
  keep_alive char(1) NOT NULL DEFAULT '0',
  redirect varchar(255) NULL,
  perms varchar(128) NULL,
  menu_type char(1) NOT NULL DEFAULT 'M',
  order_num integer NULL DEFAULT 0,
  status char(1) NOT NULL DEFAULT '0',
  PRIMARY KEY (menu_id)
);

-- 系统管理 / 用户信息表
CREATE TABLE sys_user (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY,
  username varchar(64) NOT NULL,
  password varchar(128) NOT NULL,
  nickname varchar(64) NULL,
  phone varchar(20) NULL,
  role_id bigint NULL,
  openid varchar(128) NULL,
  avatar varchar(512) NULL,
  status char(1) NOT NULL DEFAULT '0',
  password_changed_at timestamp(0) without time zone NULL,
  password_expire_at timestamp(0) without time zone NULL,
  must_change_password smallint NOT NULL DEFAULT 0,
  login_fail_count integer NOT NULL DEFAULT 0,
  locked_until timestamp(0) without time zone NULL,
  last_login_time timestamp(0) without time zone NULL,
  last_login_ip varchar(64) NULL,
  create_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time timestamp(0) without time zone NULL,
  PRIMARY KEY (user_id),
  CONSTRAINT uk_sys_user_username UNIQUE (username),
  CONSTRAINT uk_sys_user_openid UNIQUE (openid)
);

-- 系统管理 / 角色菜单关联表
CREATE TABLE sys_role_menu (
  role_menu_id bigint GENERATED BY DEFAULT AS IDENTITY,
  role_id bigint NOT NULL,
  menu_id bigint NOT NULL,
  PRIMARY KEY (role_menu_id),
  CONSTRAINT uk_role_menu UNIQUE (role_id, menu_id)
);

-- 系统管理 / 操作日志表
CREATE TABLE sys_oper_log (
  log_id bigint GENERATED BY DEFAULT AS IDENTITY,
  module varchar(64) NULL,
  oper_type varchar(32) NULL,
  oper_user varchar(64) NULL,
  oper_user_id bigint NULL,
  oper_ip varchar(64) NULL,
  request_method varchar(16) NULL,
  status char(1) NOT NULL DEFAULT '0',
  oper_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  error_msg varchar(255) NULL,
  change_summary varchar(500) NULL,
  PRIMARY KEY (log_id)
);

-- 系统管理 / 系统参数配置表
CREATE TABLE sys_config (
  config_id bigint GENERATED BY DEFAULT AS IDENTITY,
  config_key varchar(128) NOT NULL,
  config_value varchar(255) NULL,
  config_name varchar(128) NOT NULL,
  config_type varchar(64) NULL,
  remark varchar(255) NULL,
  status char(1) NOT NULL DEFAULT '0',
  update_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (config_id),
  CONSTRAINT uk_sys_config_config_key UNIQUE (config_key)
);

-- 系统管理 / 密码历史表
CREATE TABLE sys_user_password_history (
  history_id bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id bigint NOT NULL,
  password_hash varchar(128) NOT NULL,
  create_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (history_id)
);

-- 系统管理 / Refresh Token 持久化表
CREATE TABLE user_refresh_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id bigint NOT NULL,
  client_type varchar(16) NOT NULL,
  token_jti varchar(64) NOT NULL,
  token_hash varchar(128) NOT NULL,
  expires_at timestamp(0) without time zone NOT NULL,
  revoked smallint NOT NULL DEFAULT 0,
  revoked_at timestamp(0) without time zone NULL,
  replaced_by_jti varchar(64) NULL,
  device_info varchar(256) NULL,
  ip_address varchar(64) NULL,
  create_time timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_token_jti UNIQUE (token_jti)
);

